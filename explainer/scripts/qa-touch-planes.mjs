import { chromium } from "playwright"
const browser = await chromium.launch()
const mob = await browser.newPage({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true })
await mob.goto("http://localhost:4173", { waitUntil: "networkidle" })
const mch2 = mob.locator("#ch-2")
await mch2.scrollIntoViewIfNeeded()
await mob.waitForTimeout(400)
const plane = mch2.locator("svg[aria-label^='平面']").first()
const bb = await plane.boundingBox()
const cdp = await mob.context().newCDPSession(mob)
// start drag on cell 0 (top-left), move across row to cell 8
const yRow = bb.y + 13 // first row center
await cdp.send("Input.dispatchTouchEvent", { type: "touchStart", touchPoints: [{ x: bb.x + 13, y: yRow }] })
await mob.waitForTimeout(150)
const strokeAt = async (i) => plane.locator("rect").nth(i).evaluate((el) => getComputedStyle(el).stroke)
console.log("during touch on cell0: cell0 stroke:", await strokeAt(0))
await cdp.send("Input.dispatchTouchEvent", { type: "touchMove", touchPoints: [{ x: bb.x + 13 + 26 * 4, y: yRow }] })
await mob.waitForTimeout(150)
console.log("after move to cell4: cell0:", await strokeAt(0), "cell4:", await strokeAt(4))
await cdp.send("Input.dispatchTouchEvent", { type: "touchEnd", touchPoints: [] })
await mob.waitForTimeout(150)
console.log("after end: cell4:", await strokeAt(4))
await browser.close()
console.log("DONE")
