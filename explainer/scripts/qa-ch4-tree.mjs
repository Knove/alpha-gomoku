import { chromium } from "playwright"
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1400, height: 950 } })
await page.goto("http://localhost:4173", { waitUntil: "networkidle" })
const ch4 = page.locator("#ch-4")
await ch4.scrollIntoViewIfNeeded()
await page.waitForTimeout(400)
const btn = (name) => ch4.locator("button", { hasText: name }).first()
const tree = ch4.locator("svg[aria-label='MCTS 搜索树']")
await btn("单步 ×10").click()
await page.waitForTimeout(200)
console.log("at 10 sims: tree circles:", await tree.locator("circle").count(), "lines:", await tree.locator("line").count(), "viewBox:", await tree.getAttribute("viewBox"))
await btn("跑到 200").click()
await page.waitForTimeout(500)
console.log("at 200 sims: tree circles:", await tree.locator("circle").count(), "lines:", await tree.locator("line").count())
const texts = await tree.locator("text").allInnerTexts()
console.log("some tree labels:", JSON.stringify(texts.slice(0, 20)))
// check svg rendered size
const bb = await tree.boundingBox()
console.log("tree bbox:", JSON.stringify(bb))
await browser.close()
